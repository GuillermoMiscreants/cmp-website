#!/usr/bin/env node
/**
 * Makes rule-id citations clickable everywhere.
 *
 * Rules are declared beside their heading:
 *   ### Client-side scripting
 *   <!--rule: components.scripting | tier: required-->
 *
 * and cited from anywhere in the repo as `[components.scripting]`. Markdown
 * renders that as literal text unless a reference definition exists, so this
 * script appends an auto-managed block to every citing file listing only the
 * ids that file actually uses:
 *
 *   <!-- rule-links: generated ... -->
 *   [components.scripting]: ./components.md#client-side-scripting
 *   <!-- /rule-links -->
 *
 * Reference definitions are invisible when rendered, so the block costs nothing
 * visually and turns every citation into a working link.
 *
 *   node scripts/build-doc-links.mjs          rewrite the blocks
 *   node scripts/build-doc-links.mjs --check  exit 1 if any block is stale
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = join(ROOT, "docs");
const EXEMPT = [join(DOCS, "learn")];

const START = "<!-- rule-links: generated by scripts/build-doc-links.mjs — do not edit -->";
const END = "<!-- /rule-links -->";
// Anchored to end-of-file: the generated block is always last, and an unanchored
// match would swallow an example block quoted inside a fence.
const BLOCK = /\n*<!-- rule-links:[\s\S]*?<!-- \/rule-links -->\s*$/;

const walk = (dir) =>
  readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) return walk(full);
    return full.endsWith(".md") ? [full] : [];
  });

/** Blank fenced blocks: headings and declarations inside one are examples. */
const stripFences = (text) => {
  let inFence = false;
  return text
    .split(/\r?\n/)
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) {
        inFence = !inFence;
        return "";
      }
      return inFence ? "" : line;
    })
    .join("\n");
};

/**
 * Also blank inline code spans — used when scanning for citations, where a
 * bracketed id shown as code is an example.
 *
 * Deliberately NOT used for heading text: a heading like
 * "`DESIGN.md` records decisions, not values" must keep its code span, or the
 * generated anchor drops those words and stops matching the real one.
 */
const stripCode = (text) =>
  stripFences(text)
    .split(/\r?\n/)
    .map((line) => line.replace(/`[^`]*`/g, ""))
    .join("\n");

/** GitHub heading anchor: lowercase, drop punctuation, spaces to hyphens (runs preserved). */
const slug = (text) =>
  text
    .toLowerCase()
    .replace(/[`*_]/g, "")
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/\s/g, "-");

// ---------------------------------------------------------------- declarations
const moduleFiles = walk(DOCS).filter((f) => !EXEMPT.some((d) => f.startsWith(d)));
const rules = new Map(); // id -> { file, anchor }

for (const file of moduleFiles) {
  // Fences only — heading text keeps its inline code, or the anchor loses words.
  const lines = stripFences(readFileSync(file, "utf8")).split("\n");
  for (let i = 0; i < lines.length; i++) {
    const heading = lines[i].match(/^(#{2,4})\s+(.+)$/);
    if (!heading) continue;
    const decl = lines[i + 1]?.match(/<!--rule:\s*([\w.-]+)\s*\|\s*tier:\s*([\w-]+)\s*-->/);
    if (decl) rules.set(decl[1], { file, anchor: slug(heading[2]) });
  }
}

const namespaces = new Set([...rules.keys()].map((id) => id.split(".")[0]));

// ---------------------------------------------------------------- citing files
const citingFiles = [
  ...walk(DOCS).filter((f) => !EXEMPT.some((d) => f.startsWith(d))),
  ...(existsSync(join(ROOT, ".claude")) ? walk(join(ROOT, ".claude")) : []),
  ...[join(ROOT, "AGENTS.md"), join(ROOT, "README.md"), join(ROOT, "CLAUDE.md")].filter(existsSync),
];

const CITATION = /\[([a-z][\w-]*(?:\.[\w-]+)*)\](?!\(|:)/g;
const stale = [];
let written = 0;
let links = 0;

for (const file of citingFiles) {
  const rawOnDisk = readFileSync(file, "utf8");
  // Work in LF, write back in whatever the file already used. On Windows git
  // checks these out as CRLF; a script that always wrote LF rewrote every file
  // on every run, so `--check` reported all of them stale and `npm run check`
  // failed on a fresh clone — while the resulting diff was one git normalizes
  // away to nothing. Compare like for like.
  const eol = rawOnDisk.includes("\r\n") ? "\r\n" : "\n";
  const raw = rawOnDisk.replace(/\r\n/g, "\n");
  const body = raw.replace(BLOCK, "\n").trimEnd();

  const cited = new Set();
  for (const m of stripCode(body).matchAll(CITATION)) {
    if (namespaces.has(m[1].split(".")[0]) && rules.has(m[1])) cited.add(m[1]);
  }

  let next;
  if (cited.size === 0) {
    next = body + "\n";
  } else {
    const defs = [...cited].sort().map((id) => {
      const { file: target, anchor } = rules.get(id);
      let path = relative(dirname(file), target).replace(/\\/g, "/");
      if (!path.startsWith(".")) path = `./${path}`;
      return `[${id}]: ${path}#${anchor}`;
    });
    links += defs.length;
    next = `${body}\n\n${START}\n${defs.join("\n")}\n${END}\n`;
  }

  if (next !== raw) {
    if (process.argv.includes("--check")) stale.push(relative(ROOT, file).replace(/\\/g, "/"));
    else {
      writeFileSync(file, eol === "\n" ? next : next.replace(/\n/g, eol), "utf8");
      written++;
    }
  }
}

if (process.argv.includes("--check")) {
  if (stale.length) {
    console.error(`Rule-link blocks are stale in ${stale.length} file(s):`);
    for (const f of stale) console.error(`  ${f}`);
    console.error("Run: npm run docs:build");
    process.exit(1);
  }
  console.log(`Rule links are current (${rules.size} rules).`);
  process.exit(0);
}

console.log(`Rule links rebuilt: ${written} file(s) updated, ${links} definitions, ${rules.size} rules.`);
